-- Назви варіантів формату в називному відмінку, щоб вони вміщались у картках:
-- форми (Циліндрична → Циліндр, Квадратна → Квадрат, Овальна → Овал, Кругла → Круг, Трикутна → Трикутник)
-- і кольори (Біла → Білий, Зелена → Зелений, Кремова → Кремовий, Оливкова → Оливковий, Рожева → Рожевий).
-- Виконується вручну один раз у Supabase → SQL Editor. Структуру бази не змінює, лише тексти назв.
-- Щоб повернути, виконайте ці самі оновлення навпаки.

update format_options set name = case name
  when 'Циліндрична' then 'Циліндр'
  when 'Квадратна'   then 'Квадрат'
  when 'Овальна'     then 'Овал'
  when 'Кругла'      then 'Круг'
  when 'Трикутна'    then 'Трикутник'
  when 'Біла'        then 'Білий'
  when 'Зелена'      then 'Зелений'
  when 'Кремова'     then 'Кремовий'
  when 'Оливкова'    then 'Оливковий'
  when 'Рожева'      then 'Рожевий'
  else name
end
where name in ('Циліндрична', 'Квадратна', 'Овальна', 'Кругла', 'Трикутна',
               'Біла', 'Зелена', 'Кремова', 'Оливкова', 'Рожева');
