select v.name, c.id, v.stock, v.visible
from (values
  ('Троянда', 'Троянди', 40, true),
  ('Кущова троянда', 'Троянди', 14, true),
  ('Піоновидна троянда', 'Троянди', 9, true),
  ('Еустома', 'Пишні квіти', 12, true),
  ('Піон', 'Пишні квіти', 3, true),
  ('Гортензія', 'Пишні квіти', 6, false),
  ('Тюльпан', 'Весняні', 25, true),
  ('Ранункулюс', 'Весняні', 8, true),
  ('Альстромерія', 'Інші', 15, true),
  ('Хризантема', 'Інші', 0, true),
  ('Гвоздика', 'Інші', 20, true),
  ('Евкаліпт', 'Зелень', 30, true),
  ('Гіпсофіла', 'Зелень', 10, true),
